#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_DIR="$ROOT_DIR/app"
ENV_FILE="$APP_DIR/.env"

get_existing () {
  local key="$1"
  if [[ -f "$ENV_FILE" ]]; then
    grep -E "^${key}=" "$ENV_FILE" | tail -n1 | cut -d'=' -f2- || true
  fi
}

LIRA_PROJECT_ROOT="${LIRA_PROJECT_ROOT:-$(get_existing LIRA_PROJECT_ROOT)}"
LIRA_DATA_ROOT="${LIRA_DATA_ROOT:-$(get_existing LIRA_DATA_ROOT)}"
LIRA_LOGS_ROOT="${LIRA_LOGS_ROOT:-$(get_existing LIRA_LOGS_ROOT)}"
LIRA_ARCHIVE_ROOT="${LIRA_ARCHIVE_ROOT:-$(get_existing LIRA_ARCHIVE_ROOT)}"
LIRA_SECURE_ROOT="${LIRA_SECURE_ROOT:-$(get_existing LIRA_SECURE_ROOT)}"
LIRA_MODELS_ROOT="${LIRA_MODELS_ROOT:-$(get_existing LIRA_MODELS_ROOT)}"

PROJECT_ROOT="${PROJECT_ROOT:-$(get_existing PROJECT_ROOT)}"
DATA_ROOT="${DATA_ROOT:-$(get_existing DATA_ROOT)}"

VOSK_MODEL_PATH="${VOSK_MODEL_PATH:-$(get_existing VOSK_MODEL_PATH)}"
OLLAMA_URL="${OLLAMA_URL:-$(get_existing OLLAMA_URL)}"
MODEL_LIGHT="${MODEL_LIGHT:-$(get_existing MODEL_LIGHT)}"
MODEL_HEAVY="${MODEL_HEAVY:-$(get_existing MODEL_HEAVY)}"
MODEL_CODE="${MODEL_CODE:-$(get_existing MODEL_CODE)}"
LIRA_API_HOST="${LIRA_API_HOST:-$(get_existing LIRA_API_HOST)}"
LIRA_API_PORT="${LIRA_API_PORT:-$(get_existing LIRA_API_PORT)}"

LIRA_DISK_GUARD_PATH="${LIRA_DISK_GUARD_PATH:-$(get_existing LIRA_DISK_GUARD_PATH)}"
LIRA_MIN_DISK_WARN_GB="${LIRA_MIN_DISK_WARN_GB:-$(get_existing LIRA_MIN_DISK_WARN_GB)}"
LIRA_MIN_DISK_HARD_GB="${LIRA_MIN_DISK_HARD_GB:-$(get_existing LIRA_MIN_DISK_HARD_GB)}"

DEFAULT_PROJECT_ROOT="$ROOT_DIR"
DEFAULT_APP_ROOT="$APP_DIR"
DEFAULT_DATA_ROOT="$ROOT_DIR/data"
DEFAULT_LOGS_ROOT="$ROOT_DIR/logs"
DEFAULT_MODELS_ROOT="$ROOT_DIR/models"
DEFAULT_ARCHIVE_ROOT="$ROOT_DIR/archives"
DEFAULT_SECURE_ROOT="$ROOT_DIR/secure"
DEFAULT_VOSK_MODEL="$ROOT_DIR/models/vosk/vosk-model-small-pl-0.22"

LIRA_PROJECT_ROOT="${LIRA_PROJECT_ROOT:-$DEFAULT_PROJECT_ROOT}"
LIRA_DATA_ROOT="${LIRA_DATA_ROOT:-$DEFAULT_DATA_ROOT}"
LIRA_LOGS_ROOT="${LIRA_LOGS_ROOT:-$DEFAULT_LOGS_ROOT}"
LIRA_MODELS_ROOT="${LIRA_MODELS_ROOT:-$DEFAULT_MODELS_ROOT}"
LIRA_ARCHIVE_ROOT="${LIRA_ARCHIVE_ROOT:-$DEFAULT_ARCHIVE_ROOT}"
LIRA_SECURE_ROOT="${LIRA_SECURE_ROOT:-$DEFAULT_SECURE_ROOT}"

PROJECT_ROOT="${PROJECT_ROOT:-$DEFAULT_APP_ROOT}"
DATA_ROOT="${DATA_ROOT:-$DEFAULT_DATA_ROOT}"

VOSK_MODEL_PATH="${VOSK_MODEL_PATH:-$DEFAULT_VOSK_MODEL}"

OLLAMA_URL="${OLLAMA_URL:-http://127.0.0.1:11434/api/generate}"
MODEL_LIGHT="${MODEL_LIGHT:-qwen2.5:3b}"
MODEL_HEAVY="${MODEL_HEAVY:-llama3:latest}"
MODEL_CODE="${MODEL_CODE:-qwen2.5-coder:7b}"

LIRA_API_HOST="${LIRA_API_HOST:-127.0.0.1}"
LIRA_API_PORT="${LIRA_API_PORT:-8000}"

LIRA_DISK_GUARD_PATH="${LIRA_DISK_GUARD_PATH:-${DATA_ROOT:-/opt/data}}"
LIRA_MIN_DISK_WARN_GB="${LIRA_MIN_DISK_WARN_GB:-5}"
LIRA_MIN_DISK_HARD_GB="${LIRA_MIN_DISK_HARD_GB:-2}"

cat > "$ENV_FILE" <<EOF2
# Lira paths (auto-updated)
LIRA_PROJECT_ROOT=$LIRA_PROJECT_ROOT
LIRA_DATA_ROOT=$LIRA_DATA_ROOT
LIRA_LOGS_ROOT=$LIRA_LOGS_ROOT
LIRA_MODELS_ROOT=$LIRA_MODELS_ROOT
LIRA_ARCHIVE_ROOT=$LIRA_ARCHIVE_ROOT
LIRA_SECURE_ROOT=$LIRA_SECURE_ROOT

# Backward-compatible
PROJECT_ROOT=$PROJECT_ROOT
DATA_ROOT=$DATA_ROOT

# Models
VOSK_MODEL_PATH=$VOSK_MODEL_PATH

# Ollama
OLLAMA_URL=$OLLAMA_URL
MODEL_LIGHT=$MODEL_LIGHT
MODEL_HEAVY=$MODEL_HEAVY
MODEL_CODE=$MODEL_CODE

# API
LIRA_API_HOST=$LIRA_API_HOST
LIRA_API_PORT=$LIRA_API_PORT

# Disk guard — pilnuj partycji runtime (Docker1), nie systemowego / (puchnie od OS)
LIRA_DISK_GUARD_PATH=$LIRA_DISK_GUARD_PATH
LIRA_MIN_DISK_WARN_GB=$LIRA_MIN_DISK_WARN_GB
LIRA_MIN_DISK_HARD_GB=$LIRA_MIN_DISK_HARD_GB
EOF2

echo "[OK] Wrote $ENV_FILE"
